"""Emit an mcp-config.json with absolute paths and a pinned interpreter.

Use this when you would rather not ``pip install -e .`` — Claude Desktop does
not expand ``~`` or environment variables in ``command``, so the portable
config only works if the package is importable.

    python scripts/render_mcp_config.py                       # -> mcp-config.local.json
    python scripts/render_mcp_config.py -o mcp-config.json --force
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERVERS = [
    ("mining-news-mcp", "mining_agent.servers.news", {}),
    ("mineral-pdf-mcp", "mining_agent.servers.mineral_pdf", {"MINING_AGENT_PDF_PROVIDER": "offline"}),
    ("lme-price-mcp", "mining_agent.servers.lme_price", {}),
]


def build(python: str, data_dir: Path, mode: str) -> dict:
    servers = {}
    for name, module, extra_env in SERVERS:
        servers[name] = {
            "command": python,
            "args": ["-m", module],
            "env": {
                "PYTHONPATH": str(ROOT / "src"),
                "MINING_AGENT_DATA_MODE": mode,
                "MINING_AGENT_DATA_DIR": str(data_dir),
                "MINING_AGENT_LOG_LEVEL": "WARNING",
                **extra_env,
            },
        }
    return {
        "$comment": f"Generated by scripts/render_mcp_config.py for {ROOT}",
        "mcpServers": servers,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python", default=sys.executable, help="interpreter to launch the servers")
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data")
    parser.add_argument("--mode", default="offline", choices=["offline", "live", "auto"])
    parser.add_argument("-o", "--out", type=Path, default=ROOT / "mcp-config.local.json")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = parser.parse_args()

    if args.out.exists() and not args.force:
        print(f"refusing to overwrite {args.out} (pass --force)", file=sys.stderr)
        return 1

    payload = build(str(args.python), args.data_dir.resolve(), args.mode)
    args.out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    print(json.dumps(payload["mcpServers"]["mining-news-mcp"], indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
